(require '[clojure.edn :as edn] '[clojure.java.io :as io])
(def base "holes/labs/wm-contract/runs/RUN4-repair-successor-v2-selection-admission-2026-09-11/")
(defn read-edn [p] (with-open [r (java.io.PushbackReader. (io/reader p))] (let [v (edn/read r)] (assert (= ::end (edn/read {:eof ::end} r))) v)))
(defn sha [p] (format "%064x" (java.math.BigInteger. 1 (.digest (java.security.MessageDigest/getInstance "SHA-256") (java.nio.file.Files/readAllBytes (.toPath (io/file p)))))))
(let [ready (read-edn (str base "PREPARATION-READINESS.edn"))
      t (read-edn (str base "server-config.disabled.edn"))
      ref #(str (:authority-root t) "/" %)
      mpath (ref (get-in t [:manifest :ref])) m (read-edn mpath)
      trial (first (:trials m)) ppath (ref (get-in trial [:packet :path])) p (read-edn ppath)
      c (read-edn (str base "execution-cohort.disabled.edn"))
      files {:server-config-sha256 (str base "server-config.disabled.edn")
             :historical-action-sha256 (str base "historical-action.disabled.edn")
             :execution-cohort-sha256 (str base "execution-cohort.disabled.edn")
             :queue-sha256 (str base "queue.disabled.edn")
             :series-pin-sha256 mpath :task-pin-sha256 ppath
             :run-config-sha256 (ref (get-in p [:config :path]))
             :cohort-sha256 (:preregistration c)}]
 (doseq [[k path] files] (assert (= (get-in ready [:packet k]) (sha path)) k))
 (doseq [{:keys [repo path sha256]} (get-in ready [:source-provenance :runtime-source-pins])]
   (assert (= sha256 (sha (str "/home/joe/code/" (name repo) "/" path))) [repo path]))
 (assert (= (get-in t [:manifest :sha256]) (sha mpath)))
 (assert (= (:pin-sha256 trial) (get-in trial [:packet :sha256]) (sha ppath)))
 (doseq [{:keys [path sha256]} (concat (:sources p) (:source-pins m) [(:config p)])] (assert (= sha256 (sha (ref path))) path))
 (assert (= (:casting ready) (:casting t) (:casting m) (:casting p)))
 (assert (false? (:enabled? t)))
 (assert (= 1 (:target c)))
 (prn {:packet-hashes-checked (count files)
       :runtime-source-pins (count (get-in ready [:source-provenance :runtime-source-pins]))
       :source-joins :current
       :casting (:casting ready) :production-enabled? false :target 1}))
