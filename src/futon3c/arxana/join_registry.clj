(ns futon3c.arxana.join-registry
  "Data-only export for futon1b's closed edge-join vocabulary."
  (:require [clojure.java.io :as io]
            [futon3c.arxana.type-registry :as types]))

(def snapshot-resource "data/arxana/edge-join-shapes.edn")

(defn join-shapes
  "Every registered clusion revision with at least two roles. Sorted printing
  makes export byte-reproducible; no endpoint-kind semantics are changed."
  []
  (into (sorted-map)
        (for [[revision declaration] types/registry-v1
              :when (and (= :clusion (:record/kind declaration))
                         (<= 2 (count (:roles declaration))))]
          [revision (into (sorted-set) (map :role (:roles declaration)))])))

(defn export! [path]
  (io/make-parents path)
  (spit path (str ";; Generated by futon3c.arxana.join-registry/export!; do not edit.\n"
                  (pr-str (join-shapes)) "\n"))
  {:path (str path) :type-revisions (count (join-shapes))})

(defn -main [& [path]]
  (when-not path (throw (ex-info "snapshot output path required" {})))
  (prn (export! path)))
