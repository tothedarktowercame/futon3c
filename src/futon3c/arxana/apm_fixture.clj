(ns futon3c.arxana.apm-fixture
  "APM a93J02 LaTeX↔LaTeXML-oxide fixture for the two-pane code-server demo
  (M-jvm-arxana increment, 2026-11-07).

  Census: the public presentation reference is
  https://zone.hyperreal.enterprises/wip/apm-highlight-demo/ —
  apm-a93J02.tex (authored, derived from the informal-proof corpus
  data/apm-informal-proofs/apm-a93J02.md), index.html generated by
  latexml_oxide 0.7.5 (producer log retained, digest recorded), plus
  LaTeXML.css / ltx-article.css (presentation resources, not semantic
  artifacts). Exact bytes are committed under resources/arxana/apm-demo/
  with a manifest of sha256 revision ids; DOM ids are locator evidence
  only — never authority (the authority is the revision-pinned
  correspondence assertion).

  Scope evidence, honestly ranked:
  - subsection scopes (:verification :verified): the subsection title text
    appears in both the .tex source and the rendered HTML element, and the
    generated element carries the producer's DOM id.
  - paragraph scopes (:verification :partial): prose text alignment
    (longest shared normalized word run ≥ 4 words) between a blank-line
    paragraph of the .tex and a rendered <p>. Math-only or
    too-short-to-verify paragraphs are NOT registered — no invented
    symbol-level semantics."
  (:require [clojure.data.json :as json]
            [clojure.java.io :as io]
            [clojure.string :as str]
            [futon3c.arxana.correspond :as corr])
  (:import [java.nio.charset StandardCharsets]
           [java.security MessageDigest]))

(def fixture-dir "arxana/apm-demo")

(defn fixture-resource ^java.io.File [name]
  (io/file (io/resource (str fixture-dir "/" name))))

(defn- sha256-hex ^String [^bytes bs]
  (let [md (MessageDigest/getInstance "SHA-256")]
    (format "%064x" (java.math.BigInteger. 1 (.digest md bs)))))

(defn file-bytes ^bytes [^java.io.File f]
  (with-open [in (io/input-stream f)
              out (java.io.ByteArrayOutputStream.)]
    (io/copy in out)
    (.toByteArray out)))

(defn revision-id
  "Full arxana revision ID for bytes (D4 basis: sha256 over exact bytes)."
  [^bytes bs]
  (str "arxana:revision:sha256:" (sha256-hex bs)))

(defn load-manifest
  "Parsed fixture manifest (resources/arxana/apm-demo/manifest.json)."
  []
  (json/read-str (slurp (fixture-resource "manifest.json")) :key-fn keyword))

(defn verify-fixture
  "Verify the committed fixture: every artifact's bytes hash to its recorded
  sha256; every scope's dom-id occurs in the committed HTML bytes; every
  scope range lies within the .tex codepoint length and contains the first
  word of its evidence quote. Returns {:ok? true :scopes n :tex-codepoints n}
  or throws ex-info :apm-fixture/rejected with the error list."
  []
  (let [m (load-manifest)
        tex (String. (file-bytes (fixture-resource "apm-a93J02.tex")) StandardCharsets/UTF_8)
        html (String. (file-bytes (fixture-resource "index.html")) StandardCharsets/UTF_8)
        errors (concat
                (for [[logical a] (:artifacts m)
                      :let [f (fixture-resource (name logical))
                            actual (sha256-hex (file-bytes f))]
                      :when (not= actual (:sha256 a))]
                  {:error :apm-fixture/revision-mismatch
                   :artifact (name logical) :recorded (:sha256 a) :actual actual})
                (for [s (:scopes m)
                      :let [start (:tex-start s) end (:tex-end s)]
                      :when (not (and (<= 0 start end)
                                      (<= end (.codePointCount tex 0 (.length tex)))))]
                  {:error :apm-fixture/range-out-of-bounds :scope s})
                (for [s (:scopes m)
                      :when (not (str/includes? html (str "id=\"" (:dom-id s) "\"")))]
                  {:error :apm-fixture/dom-id-absent :scope (:id s) :dom-id (:dom-id s)})
                (for [s (:scopes m)
                      :let [word (first (str/split (str/lower-case (:evidence-quote s)) #"\s+"))
                            seg (str/lower-case (subs tex (min (:tex-start s) (.length tex))
                                                    (min (:tex-end s) (.length tex))))]
                      :when (or (nil? word) (not (str/includes? seg word)))]
                  {:error :apm-fixture/evidence-not-in-range :scope (:id s)}))]
    (when (seq errors)
      (throw (ex-info "APM fixture rejected"
                      {:type :apm-fixture/rejected :errors errors})))
    {:ok? true
     :scopes (count (:scopes m))
     :tex-codepoints (.codePointCount tex 0 (.length tex))}))

(defn assert-into-repository!
  "Register the APM fixture's manifestations and correspondence assertions
  into an existing in-memory correspondence repository (revision-pinned;
  no store writes, no client-minted identities — ids are the repository's
  deterministic manifestation/assertion digests). Returns
  {:assertions {id assertion} :revisions {logical revision-id}
   :tex-codepoints n :authority .. :family ..}."
  [repo]
  (let [verify-result (verify-fixture)
        m (load-manifest)
        authority (:authority m)
        family (:family m)
        producer (:producer m)
        tex-rev (revision-id (file-bytes (fixture-resource "apm-a93J02.tex")))
        html-rev (revision-id (file-bytes (fixture-resource "index.html")))
        html-origin {:origin/tool (:tool producer)
                     :origin/version (:version producer)
                     :origin/source-revisions [tex-rev (:log-digest producer)
                                               (:source-corpus producer)]}
        register! (fn [scope]
                    (let [src (corr/register-manifestation!
                               repo {:manifestation/authority authority
                                     :artifact/family-id family
                                     :manifestation/role-key (str "source/" (:id scope))
                                     :manifestation/label (str "APM a93J02 " (:id scope) " (authored TeX)")
                                     :manifestation/media-role :text/x-tex
                                     :manifestation/role :authored
                                     :manifestation/subject (:id scope)})
                          tgt (corr/register-manifestation!
                               repo {:manifestation/authority authority
                                     :artifact/family-id family
                                     :manifestation/role-key (str "html/" (:id scope))
                                     :manifestation/label (str "APM a93J02 " (:id scope) " (generated HTML)")
                                     :manifestation/media-role :text/html
                                     :manifestation/role :generated
                                     :manifestation/subject (:id scope)
                                     :manifestation/origin html-origin})
                          assertion (corr/assert-correspondence!
                                     repo {:source {:manifestation/id (:manifestation/id src)
                                                    :artifact/revision-id tex-rev
                                                    :locator {:kind :codepoint-range
                                                              :start (:tex-start scope)
                                                              :end (:tex-end scope)}}
                                           :target {:manifestation/id (:manifestation/id tgt)
                                                    :artifact/revision-id html-rev
                                                    :locator {:kind :dom-id
                                                              :value (:dom-id scope)}}
                                           :direction :source-to-target
                                           :cardinality :one-to-one
                                           :method [:quote]
                                           :verification (keyword (:verification scope))
                                           :evidence [{:type :quote
                                                       :value (:evidence-quote scope)}]
                                           :producer {:tool (:tool producer)
                                                      :version (:version producer)
                                                      :build/log-digest (:log-digest producer)}})]
                      [(:id scope) assertion]))]
    {:assertions (into {} (map register! (:scopes m)))
     :revisions {"apm-a93J02.tex" tex-rev "index.html" html-rev}
     :tex-codepoints (:tex-codepoints verify-result)
     :authority authority
     :family family}))
